#!/usr/bin/env python3
"""R77: link R76 candidate cases to R58-G dual-signed documentary witnesses.

All signatures are cryptographic attribution only. No independent physical
attestation, A6 promotion, confirmed Rf, operational dispatch, or A9 publication.
No keys are generated by this entrypoint; its sources must be supplied off-line.
"""
from __future__ import annotations

import argparse
import base64
import hashlib
import json
import os
from pathlib import Path
import re
import stat
import sys
from typing import Any

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / 'src'))
sys.path.insert(0, str(REPO / 'scripts'))
from ardrec.analytics.exact_preview import canonical, digest
from ardrec.coordination.r58g_registry_bridge import build_registry_bridge, verify_registry_bridge
from ardrec.evidence.r58g_trust_registry import registry_digest
import ardrec_p14_r76_a5_a8_offline_bridge as r76

SCHEMA = 'ardrec-p14-r77-r76-r58g-signed-documentary-intake-v1'
SOURCE = 'EXTERNAL_DOCUMENTARY_SIGNATURES_ONLY_NO_PHYSICAL_TRUTH'
HEX = re.compile(r'[0-9a-f]{64}\Z', re.ASCII)
MAX_INPUT_BYTES = 400_000
MAX_BUNDLE = 3
CLAIM_MAP = {'OBSERVADO_POSITIVO': 'MATCH',
             'OBSERVADO_NEGATIVO': 'DIFF', 'INCONCLUSO': 'INCONCLUSIVE'}

class R77Error(ValueError):
    pass

def need(ok: bool, reason: str) -> None:
    if not ok:
        raise R77Error(reason)


def read_private(path: Path, limit: int = MAX_INPUT_BYTES) -> bytes:
    """Read existing owner-private files only; never follow symlinks."""
    need(isinstance(path, Path) and path.is_absolute() and not any(
         p.is_symlink() for p in (path, *path.parents)), 'PRIVATE_PATH_SYMLINK_OR_RELATIVE')
    parent = path.parent.stat()
    need(stat.S_ISDIR(parent.st_mode) and parent.st_uid == os.getuid() and
         stat.S_IMODE(parent.st_mode) == 0o700, 'PRIVATE_PARENT_REQUIRED')
    fd = os.open(path, os.O_RDONLY | os.O_NOFOLLOW | os.O_CLOEXEC | os.O_NONBLOCK)
    try:
        s = os.fstat(fd)
        need(stat.S_ISREG(s.st_mode) and s.st_uid == os.getuid() and
             s.st_nlink == 1 and stat.S_IMODE(s.st_mode) == 0o600 and
             0 < s.st_size <= limit, 'PRIVATE_FILE_MODE_SIZE')
        raw = os.read(fd, limit + 1)
        after = os.fstat(fd)
        need(len(raw) == s.st_size and (s.st_dev,s.st_ino,s.st_mtime_ns,s.st_ctime_ns) ==
             (after.st_dev,after.st_ino,after.st_mtime_ns,after.st_ctime_ns),
             'PRIVATE_FILE_CHANGED_DURING_READ')
        return raw
    finally:
        os.close(fd)


def read_canonical(path: Path) -> Any:
    raw = read_private(path)
    need(raw.endswith(b'\n') and raw.count(b'\n') == 1,
         'CANONICAL_NEWLINE_REQUIRED')
    try:
        data = json.loads(raw[:-1], object_pairs_hook=_unique, parse_constant=_reject_const)
    except (UnicodeError, ValueError, TypeError) as exc:
        raise R77Error('INVALID_JSON') from exc
    need(raw == canonical(data) + b'\n', 'NONCANONICAL_JSON')
    return data


def _unique(pairs):
    result = {}
    for k, v in pairs:
        need(k not in result, 'DUPLICATE_KEY')
        result[k] = v
    return result


def _reject_const(x):
    raise R77Error('NONFINITE_JSON')


def bundles_from_json(raw: Any) -> list[dict[str, Any]]:
    need(type(raw) is list and len(raw) <= MAX_BUNDLE, 'SIGNED_BUNDLE_COUNT')
    result = []
    for row in raw:
        need(type(row) is dict and set(row) == {'statement','signatures','support_b64'},
             'SIGNED_BUNDLE_SCHEMA')
        b64 = row['support_b64']
        need(type(b64) is str and 0 < len(b64) <= 1_400_000, 'SUPPORT_B64_LENGTH')
        try:
            support = base64.b64decode(b64, validate=True)
        except (ValueError,base64.binascii.Error) as exc:
            raise R77Error('SUPPORT_B64_INVALID') from exc
        need(0 < len(support) <= 1_048_576 and
             base64.b64encode(support).decode('ascii') == b64,
             'SUPPORT_B64_NONCANONICAL')
        result.append({'statement':row['statement'], 'signatures':row['signatures'],
                       'support':support})
    return result


def build(receipt_dir: Path, r76_doc: dict[str, Any], registry: dict[str, Any],
          *, pinned_registry_sha256: str, signed_bundles: list[dict[str, Any]],
          prior_record_ids: tuple[str, ...], as_of_utc: str) -> dict[str, Any]:
    need(os.geteuid() != 0 and Path.cwd().resolve() == REPO,
         'NONROOT_CANONICAL_CHECKOUT_REQUIRED')
    need(type(r76_doc) is dict and r76.verify(r76_doc, receipt_dir),
         'R76_SOURCE_INVALID')
    need(type(pinned_registry_sha256) is str and HEX.fullmatch(pinned_registry_sha256) is not None,
         'REGISTRY_PIN_INVALID')
    need(type(registry) is dict and type(signed_bundles) is list and
         len(signed_bundles) <= MAX_BUNDLE, 'REGISTRY_OR_BUNDLES_INVALID')
    need(type(prior_record_ids) is tuple and
         tuple(sorted(set(prior_record_ids))) == prior_record_ids,
         'HISTORY_NOT_SORTED')
    candidates = r76_doc['candidates']
    need(type(candidates) is list and len(candidates) == 25, 'CANDIDATE_SET_INVALID')
    refs = {}
    for candidate in candidates:
        intent = candidate['a5_intent']
        key = (candidate['service_id'], candidate['a7_case_id'], intent['assessment_index'])
        need(key not in refs and candidate['service_id'] == intent['service_id'] and
             candidate['derived_case_id'] == intent['derived_case_id'],
             'R76_INTENT_BINDING_INVALID')
        refs[key] = candidate
    expected = sorted([{
        'service_id':key[0], 'case_id':key[1], 'assessment_index':key[2],
        'configuration_sha256':row['a5_intent']['configuration_sha256'],
        'method_id':row['a5_intent']['method_id'],
    } for key,row in refs.items()],key=lambda r:(r['service_id'],r['case_id'],r['assessment_index']))
    need(type(registry.get('scope')) is list and registry['scope'] == expected,
         'REGISTRY_SCOPE_DOES_NOT_MATCH_R76')
    need(registry.get('campaign_id') == 'DEV_TUTOR_001' and
         registry.get('session_id') == 'DEV_TUTOR_001',
         'CAMPAIGN_NOT_FIXED_R76_SESSION')
    seen = set()
    for bundle in signed_bundles:
        need(type(bundle) is dict and set(bundle) == {'statement','signatures','support'},
             'BUNDLE_SHAPE')
        statement = bundle['statement']
        need(type(statement) is dict and
             {'service_id','case_id','assessment_index','observed_claim','configuration_sha256',
              'method_id','session_id','record_id'} <= set(statement),
             'SIGNED_STATEMENT_SCHEMA')
        key = (statement['service_id'],statement['case_id'],statement['assessment_index'])
        need(key in refs and key not in seen, 'SIGNED_CASE_UNKNOWN_OR_DUPLICATED')
        seen.add(key)
        candidate = refs[key]
        need(candidate['declared_outcome'] in CLAIM_MAP and
             statement['observed_claim'] == CLAIM_MAP[candidate['declared_outcome']] and
             statement['configuration_sha256'] == candidate['a5_intent']['configuration_sha256'] and
             statement['method_id'] == candidate['a5_intent']['method_id'] and
             statement['session_id'] == candidate['a5_intent']['session_id'],
             'SIGNED_ASSERTION_NOT_BOUND_TO_R76_UNVERIFIED_CLAIM')
    units = r76_doc['conservative_bridge']['inputs']
    need(type(units) is list and len(units) == 25, 'R76_UNIT_COUNT_INVALID')
    # The existing R58-G validates Ed25519, pin, scope, key validity, revocation,
    # historical record IDs and, critically, conservatively preserves A6/A7/A8.
    signed = build_registry_bridge(units, signed_bundles, registry=registry,
               pinned_registry_sha256=pinned_registry_sha256,
               as_of_utc=as_of_utc, prior_record_ids=prior_record_ids)
    need(signed['signed_witness_count'] == len(signed_bundles) and
         signed['unit_count'] == 25 and signed['a6_classification'] == 'ND' and
         signed['technical_truth_accredited'] is False and
         signed['confirmed_final_risk'] is None and
         signed['applied_state_transition'] is None and
         signed['published_generation'] is None and
         signed['operational_dispatch'] is False and signed['p8_operational'] == 'NO-GO',
         'SIGNED_REVIEW_PROMOTED_UNAUTHORIZED_TRUTH')
    for dec in signed['decisions']:
        need(dec['a6_classification'] == 'ND' and dec['confirmed_rf'] is None and
             dec['a8_applied_transition'] is None, 'A6_A8_AUTHORITY_ESCALATION')
    doc = {
        'schema':SCHEMA, 'source_kind':SOURCE,
        'r75_manifest_sha256':r76_doc['r75_manifest_sha256'],
        'r76_sha256':r76_doc['sha256'],
        'external_registry_sha256':registry_digest(registry),
        'external_pin_matches_registry':True,
        'independent_pin_origin_verified':False,
        'signer_physical_independence_attested':False,
        'historical_ledger_origin_verified':False,
        'r58g_report_sha256':signed['sha256'],
        'signed_documentary_witness_count':len(signed_bundles),
        'remaining_unaccredited_units':25,
        'verified_signed_case_ids':sorted([x['statement']['case_id'] for x in signed_bundles]),
        'a6_classification':'ND', 'technical_truth_accredited':False,
        'a7_confirmed_rf':None, 'a8_applied_transitions':0,
        'a9_new_generations':0, 'p8_operational':'NO-GO',
        'operational_dispatch':False,
        'signed_documentary_review':signed,
    }
    need(len(canonical(doc)) <= 400_000, 'REPORT_TOO_LARGE')
    doc['sha256'] = digest(doc)
    return doc


def verify(report: dict[str, Any], receipt_dir: Path, r76_doc: dict[str, Any],
           registry: dict[str, Any], *, pinned_registry_sha256: str,
           signed_bundles: list[dict[str, Any]], prior_record_ids: tuple[str, ...],
           as_of_utc: str) -> bool:
    expected = build(receipt_dir,r76_doc,registry,
                     pinned_registry_sha256=pinned_registry_sha256,
                     signed_bundles=signed_bundles,prior_record_ids=prior_record_ids,
                     as_of_utc=as_of_utc)
    need(type(report) is dict and canonical(report) == canonical(expected),
         'REPORT_RECONSTRUCTION_MISMATCH')
    return True


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--receipt-dir',type=Path,required=True)
    ap.add_argument('--r76-report',type=Path,required=True)
    ap.add_argument('--registry-json',type=Path,required=True)
    ap.add_argument('--registry-pin-sha256',required=True)
    ap.add_argument('--bundles-json',type=Path,required=True)
    ap.add_argument('--prior-ids-json',type=Path,required=True)
    ap.add_argument('--as-of-utc',required=True)
    mode=ap.add_mutually_exclusive_group(required=True)
    mode.add_argument('--json',action='store_true')
    mode.add_argument('--verify-json',type=Path)
    opt=ap.parse_args(argv)
    try:
        doc=read_canonical(opt.r76_report)
        registry=read_canonical(opt.registry_json)
        bundles=bundles_from_json(read_canonical(opt.bundles_json))
        ids=read_canonical(opt.prior_ids_json)
        need(type(ids) is list and all(type(k) is str for k in ids),'PRIOR_LEDGER_SCHEMA')
        args=dict(pinned_registry_sha256=opt.registry_pin_sha256,
                  signed_bundles=bundles,prior_record_ids=tuple(ids),as_of_utc=opt.as_of_utc)
        if opt.verify_json:
            target=read_canonical(opt.verify_json)
            verify(target,opt.receipt_dir,doc,registry,**args)
            print('R77=PASS_VERIFIED_DOCUMENTARY_NO_EXECUTION')
            print('R77_SHA256='+target['sha256'])
        else:
            report=build(opt.receipt_dir,doc,registry,**args)
            sys.stdout.buffer.write(canonical(report)+b'\n')
        print('R77_P8=NO-GO',file=sys.stderr)
        print('R77_TECHNICAL_TRUTH=ND',file=sys.stderr)
    except (R77Error,ValueError,OSError,TypeError,KeyError,RuntimeError) as exc:
        print('R77=BLOCKED:'+type(exc).__name__+':'+str(exc)[:170],file=sys.stderr)
        print('R77_P8=NO-GO',file=sys.stderr)
        return 23
    return 0

if __name__ == '__main__':
    raise SystemExit(main())
